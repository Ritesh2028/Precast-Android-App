#!/bin/bash

# Android SDK Setup Script
# This script helps detect and configure the Android SDK path

set -e

ANDROID_DIR="android"
LOCAL_PROPERTIES="$ANDROID_DIR/local.properties"

echo "🔍 Searching for Android SDK..."

# Common SDK locations on macOS
SDK_PATHS=(
    "$HOME/Library/Android/sdk"
    "$HOME/Android/Sdk"
    "/Applications/Android Studio.app/Contents/jre/Contents/Home"
    "$(dirname $(dirname $(which adb 2>/dev/null || echo "")))"
)

SDK_FOUND=""

# Check each potential SDK location
for path in "${SDK_PATHS[@]}"; do
    if [ -n "$path" ] && [ -d "$path" ] && [ -d "$path/platform-tools" ]; then
        SDK_FOUND="$path"
        echo "✅ Found Android SDK at: $SDK_FOUND"
        break
    fi
done

# If not found, check ANDROID_HOME environment variable
if [ -z "$SDK_FOUND" ] && [ -n "$ANDROID_HOME" ] && [ -d "$ANDROID_HOME" ]; then
    SDK_FOUND="$ANDROID_HOME"
    echo "✅ Found Android SDK via ANDROID_HOME: $SDK_FOUND"
fi

# If still not found, prompt user or use default
if [ -z "$SDK_FOUND" ]; then
    echo "⚠️  Android SDK not found in common locations."
    echo ""
    echo "Please choose one of the following options:"
    echo "1. If you have Android Studio installed, the SDK is usually at:"
    echo "   $HOME/Library/Android/sdk"
    echo ""
    echo "2. You can set the ANDROID_HOME environment variable:"
    echo "   export ANDROID_HOME=\$HOME/Library/Android/sdk"
    echo "   export PATH=\$PATH:\$ANDROID_HOME/platform-tools:\$ANDROID_HOME/tools"
    echo ""
    echo "3. Or manually edit $LOCAL_PROPERTIES and set sdk.dir to your SDK path"
    echo ""
    
    # Use default location (user can update manually)
    SDK_FOUND="$HOME/Library/Android/sdk"
    echo "📝 Using default location: $SDK_FOUND"
    echo "   (You may need to install Android Studio or update this path)"
fi

# Create local.properties file
echo ""
echo "📝 Creating $LOCAL_PROPERTIES..."
mkdir -p "$ANDROID_DIR"

cat > "$LOCAL_PROPERTIES" << EOF
## This file is automatically generated by Android Studio.
# Do not modify this file -- YOUR CHANGES WILL BE ERASED!
#
# This file should *NOT* be checked into Version Control Systems,
# as it contains information specific to your local configuration.
#
# Location of the SDK. This is only used by Gradle.
# For customization when using a Version Control System, please read the
# header note.
sdk.dir=$SDK_FOUND
EOF

echo "✅ Created $LOCAL_PROPERTIES with SDK path: $SDK_FOUND"
echo ""
echo "💡 If the SDK path is incorrect, you can:"
echo "   1. Edit $LOCAL_PROPERTIES manually"
echo "   2. Set ANDROID_HOME environment variable and run this script again"
echo "   3. Install Android Studio from https://developer.android.com/studio"
